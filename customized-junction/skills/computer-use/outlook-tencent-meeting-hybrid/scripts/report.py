# ── Backend detection ─────────────────────────────────────────────────────

def is_claude_code():
    """True if running under Claude Code (JSONL backend), False for Hermes (SQLite)."""
    return bool(os.environ.get("CLAUDE_CODE_SESSION_ID", ""))


# ── Hermes SQLite helpers ─────────────────────────────────────────────────

HERMES_DB_PATH = None
HERMES_BASELINE_FILE = None

def _hermes_db():
    """Return the Hermes state.db path."""
    global HERMES_DB_PATH
    if HERMES_DB_PATH is None:
        HERMES_DB_PATH = os.path.join(os.environ.get("LOCALAPPDATA", ""), "hermes", "state.db")
    return HERMES_DB_PATH

def _hermes_baseline_file():
    """Return the Hermes token baseline temp file path."""
    global HERMES_BASELINE_FILE
    if HERMES_BASELINE_FILE is None:
        HERMES_BASELINE_FILE = os.path.join(tempfile.gettempdir(), "hermes_tokens_baseline.txt")
    return HERMES_BASELINE_FILE

def capture_hermes_baseline():
    """Capture current token counts from Hermes state.db and write to baseline file.

    Returns the baseline string "input|output|cache|api_count" or None on failure.
    """
    db = _hermes_db()
    baseline_path = _hermes_baseline_file()
    try:
        conn = sqlite3.connect(db, timeout=2)
        cur = conn.execute(
            "SELECT input_tokens, output_tokens, cache_read_tokens, api_call_count "
            "FROM sessions WHERE ended_at IS NULL ORDER BY started_at DESC LIMIT 1"
        )
        row = cur.fetchone()
        conn.close()
        if row is None:
            print("WARNING: No active Hermes session found — baseline not captured.",
                  file=sys.stderr)
            return None
        baseline_str = f"{row[0]}|{row[1]}|{row[2]}|{row[3]}"
        with open(baseline_path, "w") as f:
            f.write(baseline_str)
        print(f"[report] Hermes baseline written: {baseline_str}")
        return baseline_str
    except sqlite3.OperationalError as e:
        print(f"WARNING: Hermes token tracking unavailable ({e}) — baseline not captured.",
              file=sys.stderr)
        return None

def read_hermes_baseline():
    """Read the baseline string from the Hermes baseline file.

    Returns "input|output|cache|api_count" or None if not found.
    """
    baseline_path = _hermes_baseline_file()
    if not os.path.exists(baseline_path):
        return None
    try:
        with open(baseline_path, "r") as f:
            return f.read().strip()
    except IOError:
        return None

def calc_hermes_token_delta(baseline_str):
    """Calculate token delta from Hermes baseline string vs current state.db.

    Returns (input_t, output_t, cache_t, api_count_delta).
    """
    if not baseline_str:
        return 0, 0, 0, 0
    try:
        parts = baseline_str.split("|")
        base_in = int(parts[0])
        base_out = int(parts[1])
        base_cache = int(parts[2])
        base_api = int(parts[3])
    except (ValueError, IndexError):
        print("WARNING: Invalid Hermes baseline format.", file=sys.stderr)
        return 0, 0, 0, 0

    db = _hermes_db()
    try:
        conn = sqlite3.connect(db, timeout=2)
        cur = conn.execute(
            "SELECT input_tokens, output_tokens, cache_read_tokens, api_call_count "
            "FROM sessions WHERE ended_at IS NULL ORDER BY started_at DESC LIMIT 1"
        )
        row = cur.fetchone()
        conn.close()
        if row is None:
            print("WARNING: No active Hermes session for delta calculation.",
                  file=sys.stderr)
            return 0, 0, 0, 0
        delta_in = row[0] - base_in
        delta_out = row[1] - base_out
        delta_cache = row[2] - base_cache
        delta_api = row[3] - base_api
        return delta_in, delta_out, delta_cache, delta_api
    except sqlite3.OperationalError as e:
        print(f"WARNING: Hermes delta calculation failed ({e}).", file=sys.stderr)
        return 0, 0, 0, 0


# ── Path helpers ──────────────────────────────────────────────────────────

def get_session_jsonl_path():
    """Resolve the current session's JSONL file from env vars.

    Searches all project directories under ~/.claude/projects/ for the
    session JSONL — does NOT depend on os.getcwd(), so it works
    regardless of where the script is invoked from.
    """
    session_id = os.environ.get("CLAUDE_CODE_SESSION_ID", "")
    if not session_id:
        # Fallback: scan .claude/sessions/ for the active session
        home = os.path.expanduser("~")
        sessions_dir = os.path.join(home, ".claude", "sessions")
        try:
            for fname in os.listdir(sessions_dir):
                if fname.endswith(".json"):
                    fpath = os.path.join(sessions_dir, fname)
                    with open(fpath, "r") as f:
                        d = json.load(f)
                    if d.get("status") == "busy":
                        session_id = d["sessionId"]
                        break
        except FileNotFoundError:
            pass
    if not session_id:
        print("ERROR: Cannot determine CLAUDE_CODE_SESSION_ID.", file=sys.stderr)
        sys.exit(1)

    home = os.path.expanduser("~")
    projects_dir = os.path.join(home, ".claude", "projects")
    target_file = f"{session_id}.jsonl"

    # Search all project directories — cwd-independent
    if os.path.isdir(projects_dir):
        for proj_name in os.listdir(projects_dir):
            jsonl_path = os.path.join(projects_dir, proj_name, target_file)
            if os.path.isfile(jsonl_path):
                return jsonl_path

    # Should never reach here if the session is active
    print(f"ERROR: Session JSONL not found: {target_file}", file=sys.stderr)
    print(f"  Searched under: {projects_dir}", file=sys.stderr)
    sys.exit(1)


def read_jsonl(path):
    with open(path, "r", encoding="utf-8") as f:
        return [json.loads(line) for line in f]


# ── baseline subcommand ───────────────────────────────────────────────────

def cmd_baseline():
    """Print the baseline: uuid for Claude Code, token string for Hermes."""
    if is_claude_code():
        # Claude Code: print uuid of most recent assistant message
        jsonl_path = get_session_jsonl_path()
        lines = read_jsonl(jsonl_path)
        for line in reversed(lines):
            if line.get("type") == "assistant":
                print(line["uuid"])
                return
        print("ERROR: No assistant message found in session.", file=sys.stderr)
        sys.exit(1)
    else:
        # Hermes: capture current token counts to baseline file
        baseline = capture_hermes_baseline()
        if baseline:
            print(f"Baseline captured: {baseline}")
        else:
            print("WARNING: Hermes baseline not captured.", file=sys.stderr)


# ── generate subcommand ───────────────────────────────────────────────────

def calc_token_delta(jsonl_path, baseline_uuid):
    """Sum token usage from all assistant messages AFTER baseline_uuid."""
    lines = read_jsonl(jsonl_path)
    found = False
    input_t = output_t = cache_t = 0
    count = 0

    for line in lines:
        if line.get("type") != "assistant":
            continue
        if not found:
            if line.get("uuid") == baseline_uuid:
                found = True
            continue
        usage = line.get("message", {}).get("usage", {})
        input_t += usage.get("input_tokens", 0)
        output_t += usage.get("output_tokens", 0)
        cache_t += usage.get("cache_read_input_tokens", 0)
        count += 1

    if not found:
        print(f"WARNING: baseline uuid {baseline_uuid} not found in session.", file=sys.stderr)
    return input_t, output_t, cache_t, count


def get_meeting_from_calendar(date_str):
    """Query Outlook Calendar via COM for meetings on date_str (YYYY-MM-DD)."""
    try:
        import win32com.client
        outlook = dispatch_outlook_app()
        cal = outlook.GetNamespace("MAPI").GetDefaultFolder(9)  # olFolderCalendar
        items = cal.Items
        items.Sort("[Start]")
        restriction = f"[Start] >= '{date_str} 00:00' AND [Start] < '{date_str} 23:59'"
        results = []
        for item in items.Restrict(restriction):
            results.append({
                "subject": item.Subject,
                "start": str(item.Start),
                "end": str(item.End),
                "attendees": item.RequiredAttendees or "",
                "location": item.Location or "",
            })
        return results
    except Exception as e:
        print(f"WARNING: Calendar query failed: {e}", file=sys.stderr)
        return []


def extract_meeting_id(location_url):
    """Extract meeting ID from Tencent Meeting URL or Location string.

    This is a fallback path used when compose-time body extraction didn't
    store a meeting_id in state. Extracts from the URL:
      - Dashed ID in URL: https://meeting.tencent.com/dm/123-456-789
      - Plain 9-digit: https://meeting.tencent.com/dm/123456789
      - Last resort: URL slug (alias, not the dial-in number)
    """
    import re
    if not location_url:
        return ""
    # Match 9+ digits with optional dash separators: 123456789 or 123-456-789
    dash_match = re.search(r'(\d{3}(?:-\d{3}){2,})', location_url)
    if dash_match:
        return dash_match.group(1)
    # Match plain 9-digit number anywhere in the string
    plain_match = re.search(r'(?<!\d)(\d{9,10})(?!\d)', location_url)
    if plain_match:
        return plain_match.group(1)
    # Last resort: last URL path segment
    parts = location_url.rstrip("/").split("/")
    last = parts[-1] if parts else ""
    last = last.split("?")[0]
    return last


def _fmt_duration(seconds):
    """Format a duration in seconds to a human-readable string."""
    if seconds < 1:
        return "<1s"
    if seconds < 60:
        return f"{seconds}s"
    m, s = divmod(seconds, 60)
    return f"{m}m {s}s"


def print_execution_report(to, start_str, end_str, meetings, input_t,
                           output_t, cache_t, msg_count, snapshots=None,
                           started_at=None, step_times=None, lang="zh",
                           subject="", return_data=False,
                           state_meeting_id=""):
    """Print the formatted execution report to stdout.

    Called from cmd_finalize() after all step screenshots are captured.

    snapshots: optional dict mapping step key to file path, e.g.
               {"step3": "C:/.../step3_meeting_form.png"}
    step_times: optional dict mapping step key to ISO-format timestamp,
                used to calculate per-step durations.
    lang: "zh" for Chinese (default), "en" for English
    return_data: if True, return a data dict suitable for report_html.py
    state_meeting_id: meeting ID extracted from body at compose time
                       (preferred over calendar re-fetch to avoid item.Body)
    """
    snapshots = snapshots or {}
    step_times = step_times or {}

    # Calculate per-step durations
    step_durations = {}
    if step_times and started_at:
        try:
            keys = ["step1", "step2", "step3", "step4", "step5"]
            # Use earliest available timestamp as the effective start —
            # handles cases where compose.py's started_at post-dates
            # step1/step2 captures (capture_snapshot.py sets started_at
            # on first capture, but older state files may lack it).
            effective_start = datetime.fromisoformat(started_at) if isinstance(started_at, str) else started_at
            for key in keys:
                if key in step_times:
                    ts = datetime.fromisoformat(step_times[key])
                    if ts < effective_start:
                        effective_start = ts
            prev_dt = effective_start
            for key in keys:
                if key in step_times:
                    cur_dt = datetime.fromisoformat(step_times[key])
                    step_durations[key] = int((cur_dt - prev_dt).total_seconds())
                    prev_dt = cur_dt
        except (ValueError, TypeError):
            pass

    # ── i18n labels ──────────────────────────────────────────────────────
    if lang == "en":
        L = {
            "title": "══ Outlook Tencent Invitation — Execution Report ══",
            "params": "Meeting Parameters:",
            "subject": "Subject",
            "attendee": "Attendee",
            "time": "Time",
            "meeting_link": "Meeting Link",
            "meeting_id": "Meeting ID",
            "waiting_room": "Waiting Room",
            "enabled": "Enabled",
            "not_found": "<not found>",
            "pipeline": "Pipeline:",
            "step1": "Step 1   Classic Outlook + Clear Popups    ✓",
            "step2": "Step 2   Schedule Meeting + WR             ✓",
            "step3": 'Step 3   COM compose                        ✓  --to {to} --start "{start}" --end "{end}"',
            "step4": "Step 4   COM send                           ✓",
            "step5": "Step 5   Calendar Verification              ✓  {date} found {n} meeting(s), Location matched",
            "token_usage": "Token Usage:",
            "input_tokens": "Input tokens",
            "output_tokens": "Output tokens",
            "total_tokens": "Total tokens",
            "duration": "Duration",
            "status": "Status: All 5 steps passed ✓",
        }
    else:
        L = {
            "title": "══ Outlook Tencent Invitation — 执行报告 ══",
            "params": "会邀参数:",
            "subject": "主题",
            "attendee": "收件人",
            "time": "时间",
            "meeting_link": "会议链接",
            "meeting_id": "会议号",
            "waiting_room": "Waiting Room",
            "enabled": "已启用",
            "not_found": "<未找到>",
            "pipeline": "执行流水线:",
            "step1": "Step 1   确认经典Outlook + 清理弹窗   ✓",
            "step2": "Step 2   Schedule Meeting + WR        ✓",
            "step3": 'Step 3   COM compose                  ✓  --to {to} --start "{start}" --end "{end}"',
            "step4": "Step 4   COM send                     ✓",
            "step5": "Step 5   Calendar 验证                ✓  {date} 找到 {n} 个会议, Location 匹配",
            "token_usage": "Token 消耗:",
            "input_tokens": "输入 tokens",
            "output_tokens": "输出 tokens",
            "total_tokens": "总计 tokens",
            "duration": "总耗时",
            "status": "状态: 全部 5 步通过 ✓",
        }

    location = ""
    meeting_id = state_meeting_id  # Prefer compose-time extraction (no item.Body needed)
    if meetings:
        # 1. Prefer subject + start-time match (exact: same subject AND same start)
        if subject:
            for m in meetings:
                if m["subject"] == subject and start_str in m["start"]:
                    location = m["location"]
                    meeting_id = meeting_id or extract_meeting_id(location)
                    break
        # 2. Fall back: subject match only (if no subject+start match)
        if not location and subject:
            for m in meetings:
                if m["subject"] == subject:
                    location = m["location"]
                    meeting_id = meeting_id or extract_meeting_id(location)
                    break
        # 3. Fall back to start-time match (pick last = most recent)
        if not location:
            for m in reversed(meetings):
                if start_str in m["start"]:
                    location = m["location"]
                    break
        # 4. Last resort: end-time match
        if not location:
            for m in meetings:
                if end_str in m["end"]:
                    location = m["location"]
                    break
    # Fallback: extract from URL if state had no meeting_id
    if not meeting_id and location:
        meeting_id = extract_meeting_id(location)

    total = input_t + output_t

    # Extract date for display
    try:
        dt = datetime.strptime(start_str, "%Y-%m-%d %H:%M")
    except ValueError:
        try:
            dt = datetime.strptime(start_str, "%Y-%m-%d %H:%M:%S")
        except ValueError:
            dt = None
    date_str = dt.strftime("%Y-%m-%d") if dt else start_str[:10]

    # Helper: render a snapshot link as project-relative path only
    def snapshot_link(step_key):
        path = snapshots.get(step_key)
        if path:
            try:
                rel = os.path.relpath(path, os.getcwd())
            except (ValueError, OSError):
                rel = path
            rel = rel.replace("\\", "/")
            return f"\n    📷 {rel}"
