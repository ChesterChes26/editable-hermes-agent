"""
Execution report generator for the Outlook Tencent Meeting hybrid pipeline.

Dual-backend token tracking:
  - Claude Code: reads session JSONL logs (~/.claude/projects/<proj>/<session>.jsonl)
  - Hermes Agent: reads SQLite state.db (LOCALAPPDATA/hermes/state.db)

Detected automatically via CLAUDE_CODE_SESSION_ID env var:
  - Present → Claude Code JSONL path
  - Absent  → Hermes SQLite path

Token reporting is built into compose.py (baseline auto-captured on compose,
report generated by report.py finalize, called after all step screenshots).
Use report.py standalone only for debugging:

  python report.py baseline          # Print baseline (uuid for CC, tokens for Hermes)
  python report.py generate          # Generate report manually
      --to user@example.com \
      --start "2026-07-03 09:00" \
      --end "2026-07-03 11:00" \
      --baseline <uuid>
"""
import sys
import os
