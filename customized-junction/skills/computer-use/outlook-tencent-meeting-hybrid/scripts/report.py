def setup_utf8_stdout():
    """Force UTF-8 output on Windows to avoid GBK encoding errors."""
    if sys.platform == "win32":
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")


def main():
    setup_utf8_stdout()
    parser = argparse.ArgumentParser(
        description="Outlook Tencent Meeting — execution report generator"
    )
    parser.add_argument("--lang", choices=["zh", "en"], default="zh",
                        help="Output language: zh (default) or en")
    sub = parser.add_subparsers(dest="cmd", required=True)

    sub.add_parser("baseline", help="Print baseline uuid (run BEFORE task)")

    gen = sub.add_parser("generate", help="Generate full execution report (run AFTER task)")
    gen.add_argument("--to", required=True, help="Meeting attendees")
    gen.add_argument("--subject", default="", help="Meeting subject")
    gen.add_argument("--start", required=True, help="Meeting start time (YYYY-MM-DD HH:MM)")
    gen.add_argument("--end", required=True, help="Meeting end time (YYYY-MM-DD HH:MM)")
    gen.add_argument("--baseline", required=True, help="Baseline uuid from 'baseline' command")

    fin = sub.add_parser("finalize", help="Generate final report from compose state "
                        "(includes all step snapshots, cleans up state)")
    fin.add_argument("--model", default="",
                      help="LLM model name for HTML report (e.g. glm-5-turbo)")

    args = parser.parse_args()
    if args.cmd == "baseline":
        cmd_baseline()
    elif args.cmd == "generate":
        cmd_generate(args)
    elif args.cmd == "finalize":
        cmd_finalize(args)


if __name__ == "__main__":
    main()
